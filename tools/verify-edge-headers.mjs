#!/usr/bin/env node
// OPS-02 / D-08: re-proves the zone Transform Rule (docs/phase-03/edge-config.md) by real HTTP
// request against the real live edge — not by reading the ruleset back from the API. A rule
// that exists and a header that arrives are different claims: the Rulesets API can return a
// rule object all day while the rule itself has been disabled, mis-scoped, or shadowed by a
// competing zone route (see 03-05-SUMMARY.md's Task 1 finding — a stale Worker Route silently
// out-prioritized a correctly-reassigned Custom Domain for 3+ minutes). This script is the
// only thing in this repo that checks the header actually arrives.
//
// 05-11 added a fifth check: an ARCHIVED article (served by the Worker's R2-serving branch, not
// the static-asset layer) also carries the noindex header — proving the Transform Rule's
// hostname match covers Worker-generated archive responses, not just the static-asset class
// check 1 already covers. The archived path comes from `--archived-path`, or (default) is
// discovered from the local build's own `dist/archive-plan.json` via `tests/helpers/
// archive-sample.mjs` — the same discovery check 4 already does for a live homepage link, just
// sourced from the local build instead (an archived page is no longer linked from the live
// homepage once partitioned out of the static output, so there is no "live page" to crawl this
// one from). Missing input (no `--archived-path` AND no local `dist/archive-plan.json`) reports
// the check as SKIPPED with a reason — never silently reported as passed.
//
// Five checks, each independent and individually reported:
//
//   1. Static asset response on the dev host — GET https://dev.915tldr.com/version.json.
//      This is a real static file Astro emits at build time (dist/client/version.json), served
//      directly by the Workers Static Assets layer with `run_worker_first: false` — the exact
//      layer a `_headers` file WOULD cover, so this check alone would pass equally well under
//      the `_headers`-file approach D-08 rejected. It exists to prove the rule covers the case
//      the rejected approach also covers, not to distinguish D-08's choice from it.
//
//   2. A genuinely Worker-generated response — GET a nonexistent path on
//      https://admin-dev.915tldr.com/ (the Nuxt pipeline/admin app, real SSR, real server-side
//      routing). This is the check that actually matters: it is EXPECTED TO 404, and that 404
//      is generated by live application code running inside a Worker, not by the static-asset
//      layer — the exact response class a `_headers` file does NOT reliably cover and the whole
//      reason D-08 chose a zone Transform Rule instead. `dev.915tldr.com` (the Astro v2 app)
//      currently ships zero server-rendered routes (no `server:defer` islands exist yet per
//      03-01/03-05), so it has no Worker-generated response class of its own to test against —
//      using admin-dev.915tldr.com's real Nuxt SSR 404 is deliberate, not a fallback, and is a
//      *more* rigorous proof of D-08's rationale than a same-app static-asset-miss would be.
//      DO NOT "fix" this 404 — it is the point of the check, not a bug in the target.
//
//   3. Production negative control — GET https://915tldr.com/. Expects the header ABSENT. A
//      mis-scoped rule that noindexes production is the single worst outcome this plan can
//      produce and would be invisible in every other check here.
//
//   4. No application-level robots meta tag on the dev host's real content — GET whichever
//      article the LIVE deployment is currently serving (discovered by parsing the live
//      homepage — see `discoverLiveArticlePath()` below) and assert the served HTML carries no
//      `<meta name="robots">` tag. OPS-02 specifies the header must come from the edge, not from
//      the app — this guards against a future app-level workaround masquerading as a passing
//      edge check.
//
// Exits non-zero if ANY check fails, listing every failure (not just the first). A network
// error is a FAILURE, not a skip — this script never does `2>/dev/null || echo ok`.
//
// Supports --json for machine consumption (same flag as design/scripts/check-contrast.mjs).
//
// NOT wired into `pnpm test:unit` deliberately: this script depends on a live deployment
// (real DNS, a real zone Transform Rule that lives outside version control, a real Worker) and
// would fail the unit suite on a plane, in CI with no network egress, or the instant someone
// edits the zone config. It is a standing, separately-run deploy check — see
// docs/phase-03/edge-config.md's "Re-checked on every deploy, not once at sign-off" section.
//
// --- OPS-02 hardening (2026-09-23, 03-UAT.md item 2) ---
// Check 4 used to auto-discover its article URL by walking the LOCAL `dist/client/` build
// output for the one HTML file the tracer emits. That build output drifts from what is actually
// DEPLOYED: `[slug].astro`'s `getStaticPaths()` always fetches the newest article
// (`fetchLatestArticle()`, `ORDER BY published_at DESC`), and D1 ingests ~15 new articles every
// 2 hours — so a `pnpm build` run minutes after the last `wrangler deploy` already picks a
// different "newest" article than the one that shipped. Confirmed live 2026-09-23: a local build
// emitted `/crime/legal-team-prepares-for-action-...` while the deployed site was still serving
// `/education/canutillo-isd-approves-reduced-tax-rate-...`. The check then requested a path that
// exists locally but 404s on the live host, and reported a failure that was never real — the
// edge rule (independently confirmed live via direct `curl`) was fine throughout.
//
// Fixed (2026-09-23) by discovering the article from the LIVE deployment instead of the local
// build: the KV render manifest (`src/lib/server/kv-manifest.ts`) was listed in full, resolved
// against D1, and each candidate was live-probed until one answered 200.
//
// --- 04-12 hardening: discovery no longer lists the KV manifest at all ---
// `src/lib/server/kv-manifest.ts`'s own list-all-keys helper doc comment says plainly it
// "will NOT scale once Phase 4 populates the full ~41,000 article corpus" — Phase 4 has now done
// exactly that (~40k+ manifest keys), and the 2026-09-23 fix above paginates every one of those
// keys, then reads every entry back individually, before it can even start probing candidates.
// That is a KV list-keys pass plus tens of thousands of KV value reads for what this check only
// ever needed one answer from: "what does the live site actually link to right now?"
//
// The live homepage already answers that question directly, with zero D1/KV credentials and zero
// list-then-read fan-out: `discoverLiveArticlePath()` below fetches `https://<devHost>/`, takes
// the first `[data-card] a[href]` link (a real grid card — `ArticleCard.astro`'s `data-lead`
// variant is deliberately excluded, matching the plan's own wording, since the homepage's single
// lead card is a different card shape than the grid this check wants to sample), and returns that
// href verbatim. A homepage GET that returns a real article link IS the proof — nothing is
// inferred from manifest bookkeeping that could have drifted from what is actually deployed, and
// this function no longer imports `src/lib/server/d1-client.ts`, `src/lib/server/kv-manifest.ts`,
// or `src/lib/slug.ts` at all. No `CLOUDFLARE_ACCOUNT_ID`/`CLOUDFLARE_API_TOKEN`/
// `RENDER_MANIFEST_KV_NAMESPACE_ID` env vars are read by this script any more.
//
// This project shipped exactly this failure mode once already in a different form: Phase 2's
// CONT-06 defect was 248 passing tests sitting next to 253 production rows violating the very
// requirement those tests existed to enforce — a check that exists but has silently stopped
// gating. A false-negative check that "cries wolf" arrives at the same destination by a
// different road: a human starts ignoring `pnpm verify:edge` failures on principle, and the day
// the noindex rule is genuinely removed, nobody notices. Fixing the false positive is not
// cosmetic — it is what keeps this guard worth trusting.

const ROBOTS_META_RE = /<meta[^>]+name=["']robots["'][^>]*>/i;
const ARTICLE_CARD_RE = /<article[^>]*\bdata-card\b[^>]*>([\s\S]*?)<\/article>/;
const CARD_HREF_RE = /<a\s+href="([^"]+)"/;

function parseArgs(argv) {
  const args = {
    devHost: 'dev.915tldr.com',
    adminHost: 'admin-dev.915tldr.com',
    prodHost: '915tldr.com',
    devAssetPath: '/version.json',
    // Deliberately not a real route on either app — guaranteed to miss the static-asset layer
    // and fall through to admin-dev's Nuxt SSR 404 handler.
    workerNotFoundPath: '/__verify-edge-headers-worker-check__',
    articlePath: null, // auto-discovered from the live homepage (discoverLiveArticlePath) when not given
    archivedPath: null, // auto-discovered from the local build's dist/archive-plan.json when not given
    json: false,
  };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--dev-host') { args.devHost = argv[++i]; continue; }
    if (arg === '--admin-host') { args.adminHost = argv[++i]; continue; }
    if (arg === '--prod-host') { args.prodHost = argv[++i]; continue; }
    if (arg === '--dev-asset-path') { args.devAssetPath = argv[++i]; continue; }
    if (arg === '--worker-not-found-path') { args.workerNotFoundPath = argv[++i]; continue; }
    if (arg === '--article-path') { args.articlePath = argv[++i]; continue; }
    if (arg === '--archived-path') { args.archivedPath = argv[++i]; continue; }
    if (arg === '--json') { args.json = true; continue; }
    if (arg.startsWith('--dev-host=')) { args.devHost = arg.slice('--dev-host='.length); continue; }
    if (arg.startsWith('--admin-host=')) { args.adminHost = arg.slice('--admin-host='.length); continue; }
    if (arg.startsWith('--prod-host=')) { args.prodHost = arg.slice('--prod-host='.length); continue; }
    if (arg.startsWith('--dev-asset-path=')) { args.devAssetPath = arg.slice('--dev-asset-path='.length); continue; }
    if (arg.startsWith('--worker-not-found-path=')) { args.workerNotFoundPath = arg.slice('--worker-not-found-path='.length); continue; }
    if (arg.startsWith('--article-path=')) { args.articlePath = arg.slice('--article-path='.length); continue; }
    if (arg.startsWith('--archived-path=')) { args.archivedPath = arg.slice('--archived-path='.length); continue; }
  }
  return args;
}

/**
 * Discovers one archived article's canonical path from the local build's own `dist/
 * archive-plan.json` (via `tests/helpers/archive-sample.mjs`) — NOT from crawling the live
 * homepage, since an archived page is deliberately partitioned out of the static output and is
 * never linked from it. Returns `{ path }` on success or `{ error }` with a human-readable
 * reason (never throws), mirroring `discoverLiveArticlePath`'s own contract.
 */
export async function discoverArchivedArticlePath() {
  let helper;
  try {
    helper = await import('../tests/helpers/archive-sample.mjs');
  } catch (err) {
    return { error: `could not load tests/helpers/archive-sample.mjs: ${err.message}` };
  }
  try {
    const plan = helper.loadArchivePlan();
    const [sample] = helper.pickArchivedArticles(plan, 1, { marginDays: 2 });
    return { path: sample.path };
  } catch (err) {
    return { error: err instanceof Error ? err.message : String(err) };
  }
}

/**
 * Discovers the article path actually served by the live `devHost` deployment by parsing the
 * live homepage itself — see the header comment's "04-12 hardening" section for the full
 * rationale and the KV-listing approach this replaced. Returns `{ path }` on success or
 * `{ error }` with a human-readable reason on any failure (never throws) so the caller can
 * report a normal failing check rather than crashing.
 *
 * Takes the first `[data-card] a[href]` link on the homepage — a real grid card
 * (`ArticleCard.astro`'s `default`/`compact` variants), deliberately not the single `[data-lead]`
 * card, which is a different markup shape. A homepage GET that names a real article link IS the
 * answer; nothing is inferred from build-time bookkeeping that could have drifted from what is
 * actually deployed.
 */
export async function discoverLiveArticlePath(devHost) {
  const homeUrl = `https://${devHost}/`;
  let res;
  try {
    res = await fetch(homeUrl, { redirect: 'manual' });
  } catch (err) {
    return { error: `network error fetching homepage ${homeUrl}: ${err.message}` };
  }
  if (res.status !== 200) {
    return { error: `homepage ${homeUrl} responded ${res.status}, expected 200` };
  }

  let html;
  try {
    html = await res.text();
  } catch (err) {
    return { error: `failed reading homepage body: ${err.message}` };
  }

  const cardMatch = html.match(ARTICLE_CARD_RE);
  if (!cardMatch) {
    return { error: `no [data-card] article element found on the live homepage (${homeUrl})` };
  }

  const hrefMatch = cardMatch[1].match(CARD_HREF_RE);
  if (!hrefMatch) {
    return { error: 'found a [data-card] article on the live homepage but no <a href> inside it' };
  }

  return { path: hrefMatch[1] };
}

async function fetchHeader(url, headerName) {
  const res = await fetch(url, { redirect: 'manual' });
  return { status: res.status, headerValue: res.headers.get(headerName), body: await res.text() };
}

export async function runChecks(args) {
  const checks = [];

  // 1. Static asset response on the dev host.
  {
    const url = `https://${args.devHost}${args.devAssetPath}`;
    const name = 'static asset response carries noindex (dev host)';
    try {
      const { status, headerValue } = await fetchHeader(url, 'x-robots-tag');
      const pass = status === 200 && /noindex/i.test(headerValue || '');
      checks.push({ name, url, expected: 'x-robots-tag: noindex, status 200', observed: `status ${status}, x-robots-tag: ${headerValue ?? '(absent)'}`, pass });
    } catch (err) {
      checks.push({ name, url, expected: 'x-robots-tag: noindex, status 200', observed: `network error: ${err.message}`, pass: false });
    }
  }

  // 2. Worker-generated response (real SSR 404 on the admin-dev Nuxt app — see header comment).
  {
    const url = `https://${args.adminHost}${args.workerNotFoundPath}`;
    const name = 'Worker-generated 404 carries noindex (admin-dev host, expected to 404)';
    try {
      const { status, headerValue } = await fetchHeader(url, 'x-robots-tag');
      const pass = status === 404 && /noindex/i.test(headerValue || '');
      checks.push({ name, url, expected: 'x-robots-tag: noindex, status 404 (expected, not a bug)', observed: `status ${status}, x-robots-tag: ${headerValue ?? '(absent)'}`, pass });
    } catch (err) {
      checks.push({ name, url, expected: 'x-robots-tag: noindex, status 404', observed: `network error: ${err.message}`, pass: false });
    }
  }

  // 3. Production negative control — header must be ABSENT.
  {
    const url = `https://${args.prodHost}/`;
    const name = 'production negative control (header absent)';
    try {
      const { status, headerValue } = await fetchHeader(url, 'x-robots-tag');
      const pass = status === 200 && !headerValue;
      checks.push({ name, url, expected: 'x-robots-tag absent, status 200', observed: `status ${status}, x-robots-tag: ${headerValue ?? '(absent)'}`, pass });
    } catch (err) {
      checks.push({ name, url, expected: 'x-robots-tag absent, status 200', observed: `network error: ${err.message}`, pass: false });
    }
  }

  // 4. No application-level robots meta tag on the dev host's real content. Article path is
  //    discovered from the LIVE homepage (discoverLiveArticlePath), not a local build and not a
  //    KV listing — see discoverLiveArticlePath()'s doc comment and this file's header comment.
  {
    const name = 'no app-level <meta name="robots"> on the dev host (header must come from the edge)';
    let articlePath = args.articlePath;
    let discoveryError = null;
    if (!articlePath) {
      const discovered = await discoverLiveArticlePath(args.devHost);
      articlePath = discovered.path ?? null;
      discoveryError = discovered.error ?? null;
    }
    if (!articlePath) {
      checks.push({ name, url: `https://${args.devHost}/`, expected: 'no <meta name="robots"> tag', observed: `could not discover a live article path — ${discoveryError}`, pass: false });
    } else {
      const url = `https://${args.devHost}${articlePath}`;
      try {
        const { status, body } = await fetchHeader(url, 'x-robots-tag');
        const hasMetaTag = ROBOTS_META_RE.test(body);
        const pass = status === 200 && !hasMetaTag;
        checks.push({ name, url, expected: 'no <meta name="robots"> tag, status 200', observed: `status ${status}, robots meta tag ${hasMetaTag ? 'PRESENT (fail)' : 'absent'}`, pass });
      } catch (err) {
        checks.push({ name, url, expected: 'no <meta name="robots"> tag, status 200', observed: `network error: ${err.message}`, pass: false });
      }
    }
  }

  // 5. An ARCHIVED article (Worker's R2-serving branch, not the static-asset layer) also carries
  //    noindex — see this file's header comment for why discovery differs from check 4's.
  //    Missing input is reported as SKIPPED with a reason, never as passed.
  {
    const name = 'archived article response carries noindex (dev host, Worker-served from R2)';
    let archivedPath = args.archivedPath;
    let discoveryError = null;
    if (!archivedPath) {
      const discovered = await discoverArchivedArticlePath();
      archivedPath = discovered.path ?? null;
      discoveryError = discovered.error ?? null;
    }
    if (!archivedPath) {
      checks.push({
        name,
        url: null,
        expected: 'x-robots-tag: noindex, status 200',
        observed: `skipped — no --archived-path given and could not discover one locally: ${discoveryError}`,
        pass: false,
        skipped: true,
      });
    } else {
      const url = `https://${args.devHost}${archivedPath}`;
      try {
        const { status, headerValue } = await fetchHeader(url, 'x-robots-tag');
        const pass = status === 200 && /noindex/i.test(headerValue || '');
        checks.push({ name, url, expected: 'x-robots-tag: noindex, status 200', observed: `status ${status}, x-robots-tag: ${headerValue ?? '(absent)'}`, pass });
      } catch (err) {
        checks.push({ name, url, expected: 'x-robots-tag: noindex, status 200', observed: `network error: ${err.message}`, pass: false });
      }
    }
  }

  return checks;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const start = Date.now();
  const checks = await runChecks(args);
  const durationMs = Date.now() - start;
  // A skipped check (missing input, e.g. no local dist/archive-plan.json and no --archived-path)
  // is neither a pass nor a failure — it never counts toward "all checks passed" being reported
  // true, but it also doesn't fail the whole run the way a genuine FAIL does, matching the
  // must_have's "reports the check as skipped ... never as passed" (not "never blocks the run").
  const ok = checks.every((c) => c.pass || c.skipped);
  const allPassed = checks.every((c) => c.pass);

  if (args.json) {
    console.log(JSON.stringify({ ok, allPassed, durationMs, checks }, null, 2));
  } else {
    console.log(`[verify-edge] ${checks.length} checks, ${durationMs}ms`);
    for (const c of checks) {
      const label = c.skipped ? 'SKIP' : c.pass ? 'PASS' : 'FAIL';
      console.log(`  ${label}  ${c.name}`);
      console.log(`        url:      ${c.url ?? '(none — see observed)'}`);
      console.log(`        expected: ${c.expected}`);
      console.log(`        observed: ${c.observed}`);
    }
    console.log(
      allPassed
        ? '[verify-edge] all checks passed'
        : ok
          ? '[verify-edge] all checks passed or skipped (no failures)'
          : '[verify-edge] one or more checks FAILED'
    );
  }

  process.exitCode = ok ? 0 : 1;
}

// Only run as a CLI when invoked directly — a future test suite can import
// runChecks/discoverLiveArticlePath and drive them without spawning a process, matching
// tools/check-config-guards.mjs's pattern.
if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
